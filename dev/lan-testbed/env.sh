#!/usr/bin/env bash
# Shared settings for the disposable public testbed.
set -euo pipefail

LAN_TESTBED_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$LAN_TESTBED_ROOT/../.." && pwd)"

JABU_LAN_DOMAIN="${JABU_LAN_DOMAIN:-organic.ddnsfree.com}"
JABU_LAN_IP="${JABU_LAN_IP:-192.168.68.56}"
JABU_LAN_STATE="${JABU_LAN_STATE:-$LAN_TESTBED_ROOT/state}"

STATE="$JABU_LAN_STATE"
DOMAIN="$JABU_LAN_DOMAIN"
LAN_IP="$JABU_LAN_IP"

PROSODY_CONFIG="$STATE/prosody.cfg.lua"
PROSODY_C2S_PORT=5222
PROSODY_DIRECT_TLS_PORT=5223
PROSODY_HTTP_PORT=5280

HOST_PORT=8088
GALENE_PORT=18444
GALENE_UDP_RANGE="50000-50100"
TURN_PORT=3478
TURN_RELAY_RANGE="50200-50300"
TURN_USER="jabu"
CADDY_HTTP_PORT=80
CADDY_HTTPS_PORT=443

export LAN_TESTBED_ROOT REPO_ROOT STATE DOMAIN LAN_IP
export PROSODY_CONFIG PROSODY_C2S_PORT PROSODY_DIRECT_TLS_PORT PROSODY_HTTP_PORT
export HOST_PORT GALENE_PORT GALENE_UDP_RANGE TURN_PORT TURN_RELAY_RANGE TURN_USER
export CADDY_HTTP_PORT CADDY_HTTPS_PORT
